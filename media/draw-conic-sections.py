"""Generate four exact cone-plane intersections as standalone TikZ.

Run from the repository root:
    python media/draw-conic-sections.py
    xelatex -output-directory=media media/conic-sections.tex

World surface: x^2+y^2=a^2 z^2, |z|<=height.
Section plane: z=m*x+c. The cone is truncated only for drawing.
All panels use one orthographic camera; dashed curves lie on the back surface.
"""
from math import acos, cos, pi, sin, tan
from pathlib import Path

HERE = Path(__file__).resolve().parent
A = 1.2
HEIGHT = 1.7
C = 0.7
AZIMUTH = -120 * pi / 180
ELEVATION = 15 * pi / 180
CAMERA = (cos(AZIMUTH)*cos(ELEVATION), sin(AZIMUTH)*cos(ELEVATION), sin(ELEVATION))
RIGHT = (-sin(AZIMUTH), cos(AZIMUTH), 0)
UP = (-cos(AZIMUTH)*sin(ELEVATION), -sin(AZIMUTH)*sin(ELEVATION), cos(ELEVATION))
PANELS = [('圆', 0.0), ('椭圆', 0.38), ('抛物线', 1/A), ('双曲线', 1.55)]


def dot(u, v):
    return sum(a*b for a, b in zip(u, v))


def project(point):
    return dot(point, RIGHT), dot(point, UP)


def coord(point):
    x, y = project(point)
    return f'({x:.5f},{y:.5f})'


def path(points, style, close=False):
    if len(points) < 2:
        return ''
    return '\\draw['+style+'] '+ ' -- '.join(coord(p) for p in points) + (' -- cycle' if close else '') + ';'


def runs(samples):
    """Separate invalid and front/back spans without bridging asymptotes."""
    current, last = [], None
    for point, visible in samples:
        if point is None:
            if current:
                yield current, last
            current, last = [], None
        elif current and visible != last:
            yield current+[point], last
            current, last = [point], visible
        else:
            current.append(point)
            last = visible
    if current:
        yield current, last


def section_samples(m, sign, count=1600):
    result = []
    for i in range(count+1):
        theta = 2*pi*i/count
        denominator = sign-A*m*cos(theta)
        t = C/denominator if denominator > 1e-10 else -1
        if not 0 < t <= HEIGHT:
            result.append((None, False))
            continue
        p = (A*t*cos(theta), A*t*sin(theta), sign*t)
        assert abs(p[0]**2+p[1]**2-A*A*p[2]**2) < 1e-10
        assert abs(p[2]-m*p[0]-C) < 1e-10
        facing = dot((cos(theta), sin(theta), -sign*A), CAMERA) >= 0
        result.append((p, facing))
    return result


pieces = []
counts = []
for index, (name, m) in enumerate(PANELS):
    samples = [section_samples(m, sign) for sign in (1, -1)]
    valid = [p for group in samples for p, _ in group if p is not None]
    assert valid
    discriminant = A*A*m*m-1
    if name in {'圆', '椭圆'}: assert discriminant < 0
    elif name == '抛物线': assert abs(discriminant) < 1e-12
    else: assert discriminant > 0
    counts.append((name, len(valid)))
    xshift, yshift = (index % 2)*5.8, -(index // 2)*5.55
    pieces.append(f'\\begin{{scope}}[shift={{({xshift:.2f},{yshift:.2f})}}]')
    pieces.append(f'% {name}: z={m:.12g}x+{C}; x^2+y^2={A*A}z^2.')
    for sign in (1, -1):
        delta = acos(sign*A*tan(ELEVATION))
        t1, t2 = AZIMUTH-delta, AZIMUTH+delta
        rim = [(A*HEIGHT*cos(t), A*HEIGHT*sin(t), sign*HEIGHT) for t in
               [t1+(t2-t1)*i/120 for i in range(121)]]
        pieces.append(path([(0, 0, 0)]+rim, 'draw=none,fill=conegray,fill opacity=0.12', True))
    pieces.append(path([(0,0,-HEIGHT*1.14),(0,0,HEIGHT*1.15)], 'axisline'))
    xmin, xmax = min(p[0] for p in valid)-0.22, max(p[0] for p in valid)+0.22
    ymax = max(abs(p[1]) for p in valid)+0.20
    if m:
        xmin=max(xmin,(-HEIGHT*1.06-C)/m)
        xmax=min(xmax,(HEIGHT*1.06-C)/m)
    plane=[(x,y,m*x+C) for x,y in [(xmin,-ymax),(xmax,-ymax),(xmax,ymax),(xmin,ymax)]]
    pieces.append(path(plane, 'plane', True))
    for sign in (1, -1):
        delta=acos(sign*A*tan(ELEVATION))
        for theta in (AZIMUTH-delta, AZIMUTH+delta):
            pieces.append(path([(0,0,0),(A*HEIGHT*cos(theta),A*HEIGHT*sin(theta),sign*HEIGHT)],'outline'))
        rim=[]
        for i in range(361):
            theta=2*pi*i/360
            point=(A*HEIGHT*cos(theta),A*HEIGHT*sin(theta),sign*HEIGHT)
            front=cos(theta-AZIMUTH)>=0
            rim.append((point,front))
        for points,front in runs(rim):
            pieces.append(path(points,'outline' if front else 'backline'))
    curve_runs=[(points,front) for group in samples for points,front in runs(group)]
    for front in (False, True):
        for points,visible in curve_runs:
            if visible==front:
                pieces.append(path(points,'sectionfront' if front else 'sectionback'))
    pieces.append('\\fill[conegray] (0,0) circle (0.65pt);')
    pieces.append(f'\\node[font=\\fontsize{{9.5pt}}{{12pt}}\\selectfont] at (0,-2.88) {{{name}}};')
    pieces.append('\\end{scope}')

source=r'''% Generated by draw-conic-sections.py. Change the geometry in that script.
\documentclass[tikz,border=2pt]{standalone}
\usepackage[UTF8,fontset=windows]{ctex}
\definecolor{conegray}{HTML}{707A84}
\definecolor{sectionblue}{HTML}{245C86}
\definecolor{planegray}{HTML}{B6C9CF}
\begin{document}
\special{pdf:minorversion 5}
\begin{tikzpicture}[
    line join=round,line cap=round,
    outline/.style={draw=conegray,line width=0.45pt},
    backline/.style={draw=conegray!65,line width=0.35pt,dash pattern=on 1.5pt off 1.6pt},
    axisline/.style={draw=conegray!55,line width=0.3pt,dash pattern=on 3pt off 2pt},
    plane/.style={draw=planegray!85!black,line width=0.35pt,fill=planegray,fill opacity=0.27},
    sectionfront/.style={draw=sectionblue,line width=1.35pt},
    sectionback/.style={draw=sectionblue!85,line width=1.05pt,dash pattern=on 2.4pt off 1.8pt}
]
'''+ '\n'.join(pieces) + '\n\\end{tikzpicture}\n\\end{document}\n'
(HERE/'conic-sections.tex').write_text(source,encoding='utf-8')
print('Generated conic-sections.tex; exact intersection samples:',counts)
